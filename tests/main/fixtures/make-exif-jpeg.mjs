import { writeFile } from "node:fs/promises";
import piexifjs from "piexifjs";
import sharp from "sharp";

/**
 * Creates a JPEG with an embedded EXIF thumbnail.
 * @param {string} outPath - Destination file.
 * @returns {Promise<void>}
 */
export async function makeExifJpeg(outPath) {
  const main = await sharp({
    create: { width: 120, height: 80, channels: 3, background: "#c81e1e" },
  })
    .jpeg({ quality: 85 })
    .toBuffer();
  const thumb = await sharp({
    create: { width: 32, height: 32, channels: 3, background: "#1ec81e" },
  })
    .jpeg({ quality: 60 })
    .toBuffer();

  const exifBytes = piexifjs.dump({
    "0th": { [piexifjs.ImageIFD.Software]: "meshviewer fixture" },
    Exif: { [piexifjs.ExifIFD.UserComment]: "ASCII\0\0\0fixture generated by piexifjs" },
    "1st": {},
    thumbnail: thumb.toString("binary"),
  });
  const data = Buffer.from(piexifjs.insert(exifBytes, main.toString("binary")), "binary");
  await writeFile(outPath, data);
  return thumb;
}

/**
 * Creates a plain JPEG without EXIF data.
 * @param {string} outPath - Destination file.
 * @returns {Promise<void>}
 */
export async function makePlainJpeg(outPath) {
  const main = await sharp({
    create: { width: 120, height: 80, channels: 3, background: "#1e1ec8" },
  })
    .jpeg({ quality: 85 })
    .toBuffer();
  await writeFile(outPath, main);
}
